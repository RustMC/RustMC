pub const STACK_MERGE_EXPAND_VERTICAL: f64 = 0.25;

/// Total number of player inventory slots (9 hotbar + 27 main inventory).
pub const TOTAL_SLOT_COUNT: usize = 36;

/// Number of hotbar slots (slots 0..=8).
pub const HOTBAR_SLOT_COUNT: usize = 9;

/// Number of main inventory slots (slots 9..=35).
pub const MAIN_SLOT_COUNT: usize = 27;

/// Java 26.3 clientbound `minecraft:take_item_entity` packet ID (official 26.3 packets report: 127).
pub const TAKE_ITEM_ENTITY_PACKET_ID: u32 = TAKE_ITEM_ENTITY;

/// Tolerance threshold for floating-point collision tests.
const EPSILON: f64 = 1e-7;

/// Velocity threshold below which near-zero speeds are clamped to zero.
const VELOCITY_REST_THRESHOLD: f64 = 1e-6;

/// Errors returned by inventory transactions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InventoryError {
    /// Slot index is outside the valid inventory range `0..=35`.
    InvalidSlot(u8),
    /// Slot index is outside the valid hotbar range `0..=8`.
    InvalidHotbarSlot(u8),
    /// Stack validation failed.
    InvalidStack(ItemStackError),
    /// Held slot does not contain enough items.
    InsufficientItems { requested: u16, available: u16 },
    /// Inventory has no available space to accept items.
    InventoryFull,
}

impl fmt::Display for InventoryError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidSlot(slot) => write!(f, "inventory slot {slot} is out of bounds (0..=35)"),
            Self::InvalidHotbarSlot(slot) => {
                write!(f, "hotbar slot {slot} is out of bounds (0..=8)")
            }
            Self::InvalidStack(err) => write!(f, "invalid item stack: {err}"),
            Self::InsufficientItems {
                requested,
                available,
            } => {
                write!(
                    f,
                    "insufficient items: requested {requested}, but only {available} available"
                )
            }
            Self::InventoryFull => write!(f, "inventory has no available space"),
        }
    }
}

impl std::error::Error for InventoryError {}

/// Player inventory managing 36 slots (9 hotbar + 27 main inventory).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PlayerInventory {
    slots: [Option<ItemStack>; TOTAL_SLOT_COUNT],
    held_slot: u8,
    revision: u64,
}

impl Default for PlayerInventory {
    fn default() -> Self {
        Self::new()
    }
}

impl PlayerInventory {
    /// Construct an empty player inventory.
    pub const fn new() -> Self {
        Self {
            slots: [const { None }; TOTAL_SLOT_COUNT],
            held_slot: 0,
            revision: 0,
        }
    }

    /// The currently active held hotbar slot (`0..=8`).
    pub const fn held_slot(&self) -> u8 {
        self.held_slot
    }

    /// Select an active hotbar slot (`0..=8`).
    pub fn set_held_slot(&mut self, slot: u8) -> Result<(), InventoryError> {
        if slot >= HOTBAR_SLOT_COUNT as u8 {
            return Err(InventoryError::InvalidHotbarSlot(slot));
        }
        self.held_slot = slot;
        Ok(())
    }

    /// Monotonic revision counter tracking inventory mutations.
    pub const fn revision(&self) -> u64 {
        self.revision
    }

    /// Reference to all 36 slots.
    pub fn slots(&self) -> &[Option<ItemStack>] {
        &self.slots
    }

    /// Reference to a specific slot if valid.
    pub fn get_slot(&self, slot: u8) -> Option<&ItemStack> {
        if (slot as usize) < TOTAL_SLOT_COUNT {
            self.slots[slot as usize].as_ref()
        } else {
            None
        }
    }

    /// Assign an item stack directly to a specific slot.
    pub fn set_slot(&mut self, slot: u8, stack: Option<ItemStack>) -> Result<(), InventoryError> {
        if (slot as usize) >= TOTAL_SLOT_COUNT {
            return Err(InventoryError::InvalidSlot(slot));
        }
        self.slots[slot as usize] = stack;
        self.revision = self
            .revision
            .checked_add(1)
            .expect("inventory revision overflow");
        Ok(())
    }

    /// Attempt to insert an item stack into inventory slots:
    /// 1. Top up existing compatible partial stacks (`count < max_stack`) across slots 0..36.
    /// 2. Place remainder into empty slots across slots 0..36.
    ///
    /// Returns the number of items successfully accepted by the inventory.
    pub fn insert_stack(&mut self, stack: &ItemStack) -> u16 {
        let mut remaining = stack.count();

        // Pass 1: top up compatible partial stacks
        for slot in &mut self.slots {
            if remaining == 0 {
                break;
            }
            if let Some(existing) = slot
                && existing.can_stack_with(stack)
                && existing.count() < existing.max_stack()
            {
                remaining = existing.add(remaining);
            }
        }

        // Pass 2: fill empty slots
        for slot in &mut self.slots {
            if remaining == 0 {
                break;
            }
            if slot.is_none() {
                let to_add = remaining.min(stack.max_stack());
                let new_stack = ItemStack::try_new(stack.item(), to_add, stack.max_stack())
                    .expect("sub-stack from validated ItemStack is valid");
                *slot = Some(new_stack);
                remaining -= to_add;
            }
        }

        let collected = stack.count() - remaining;
        if collected > 0 {
            self.revision = self
                .revision
                .checked_add(1)
                .expect("inventory revision overflow");
        }
        collected
    }

    /// Transactional method to grant items, returning the unplaced remainder count or `InventoryFull`.
    pub fn grant_item(
        &mut self,
        item: impl Into<String>,
        count: u16,
        max_stack: u16,
    ) -> Result<u16, InventoryError> {
        let stack =
            ItemStack::try_new(item, count, max_stack).map_err(InventoryError::InvalidStack)?;
        let placed = self.insert_stack(&stack);
        if placed == 0 {
            return Err(InventoryError::InventoryFull);
        }
        Ok(count - placed)
    }

    /// Total count of matching items held across all slots.
    pub fn total_count_of(&self, item: &str) -> u32 {
        self.slots
            .iter()
            .flatten()
            .filter(|s| s.item() == item)
            .map(|s| u32::from(s.count()))
            .sum()
    }

    /// Check if all 36 inventory slots are currently empty.
    pub fn is_empty(&self) -> bool {
        self.slots.iter().all(Option::is_none)
    }
}

/// Java Edition clientbound `minecraft:take_item_entity` packet payload (packet ID 127 / 0x7F).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TakeItemEntityPacket {
    pub collected_entity_id: u32,
    pub collector_entity_id: u32,
    pub pickup_item_count: u32,
}

impl TakeItemEntityPacket {
    /// Construct a new `TakeItemEntityPacket`.
    pub const fn new(
        collected_entity_id: u32,
        collector_entity_id: u32,
        pickup_item_count: u32,
    ) -> Self {
        Self {
            collected_entity_id,
            collector_entity_id,
            pickup_item_count,
        }
    }

    /// Encode the body payload (without length prefix or packet ID framing).
    pub fn encode_payload(&self) -> Vec<u8> {
        let mut body = Vec::new();
        put_varint(self.collected_entity_id, &mut body);
        put_varint(self.collector_entity_id, &mut body);
        put_varint(self.pickup_item_count, &mut body);
        body
    }

    /// Encode the fully framed packet: `[VarInt length] [VarInt 0x7F] [payload]`.
    pub fn encode_packet(&self) -> Vec<u8> {
        frame(TAKE_ITEM_ENTITY_PACKET_ID, &self.encode_payload())
    }

    /// Decode the packet payload from a slice of bytes using `java_wire::read_varint`.
    pub fn decode_payload(input: &[u8]) -> Result<Self, String> {
        fn read_next(buf: &[u8]) -> Result<(u32, &[u8]), String> {
            match read_varint(buf) {
                Ok(Some((val, len))) => Ok((val, &buf[len..])),
                Ok(None) => Err("unexpected EOF while reading VarInt".to_owned()),
                Err(err) => Err(format!("malformed VarInt: {err:?}")),
            }
        }
        let (collected_entity_id, rest) = read_next(input)?;
        let (collector_entity_id, rest) = read_next(rest)?;
        let (pickup_item_count, rest) = read_next(rest)?;
        if !rest.is_empty() {
            return Err("trailing bytes in TakeItemEntity packet payload".to_owned());
        }
        Ok(Self {
            collected_entity_id,
            collector_entity_id,
            pickup_item_count,
        })
    }
}

/// Event emitted when an item is successfully picked up by a player.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ItemPickupEvent {
    pub collected_entity_id: u32,
    pub collector_entity_id: u32,
    pub item: String,
    pub count: u16,
    pub packet: TakeItemEntityPacket,
}

/// Result returned from an attempted item collection by a player.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ItemPickupResult {
    pub collected_count: u16,
    pub remaining_count: u16,
    pub event: Option<ItemPickupEvent>,
}

impl ItemPickupResult {
    /// Helper for no collection occurring.
    pub const fn none(remaining_count: u16) -> Self {
        Self {
            collected_count: 0,
            remaining_count,
            event: None,
        }
    }

    /// Whether any items were successfully collected.
    pub const fn is_collected(&self) -> bool {
        self.collected_count > 0
    }
}

/// A dropped item entity floating in the world.
#[derive(Debug, Clone, PartialEq)]
pub struct ItemEntity {
    id: u32,
    position: [f64; 3],
    velocity: [f64; 3],
    stack: Option<ItemStack>,
    age: u32,
    pickup_delay: u32,
    on_ground: bool,
    dead: bool,
}

impl ItemEntity {
    /// Construct a new `ItemEntity` at the given position with 0 pickup delay.
    pub fn new(id: u32, position: [f64; 3], stack: ItemStack) -> Self {
        Self {
            id,
            position,
            velocity: [0.0, 0.0, 0.0],
            stack: Some(stack),
            age: 0,
            pickup_delay: 0,
            on_ground: false,
            dead: false,
        }
    }

    /// Construct an `ItemEntity` dropped by a player (pickup delay 40 ticks).
    pub fn dropped_by_player(
        id: u32,
        position: [f64; 3],
        velocity: [f64; 3],
        stack: ItemStack,
    ) -> Self {
        Self {
            id,
            position,
            velocity,
            stack: Some(stack),
            age: 0,
            pickup_delay: PLAYER_DROP_PICKUP_DELAY,
            on_ground: false,
            dead: false,
        }
    }

    /// Construct an `ItemEntity` dropped from a broken block (pickup delay 10 ticks).
    pub fn dropped_by_block_break(
        id: u32,
        position: [f64; 3],
        velocity: [f64; 3],
        stack: ItemStack,
    ) -> Self {
        Self {
            id,
            position,
            velocity,
            stack: Some(stack),
            age: 0,
            pickup_delay: BLOCK_BREAK_PICKUP_DELAY,
            on_ground: false,
            dead: false,
        }
    }

    /// Set initial velocity.
    pub const fn with_velocity(mut self, velocity: [f64; 3]) -> Self {
        self.velocity = velocity;
        self
    }

    /// Set initial pickup delay in ticks.
    pub const fn with_pickup_delay(mut self, pickup_delay: u32) -> Self {
        self.pickup_delay = pickup_delay;
        self
    }

    /// Set initial age in ticks.
    pub const fn with_age(mut self, age: u32) -> Self {
        self.age = age;
        self
    }

    /// Unique entity ID.
    #[inline]
    pub const fn id(&self) -> u32 {
        self.id
    }

    /// Current entity position `[x, y, z]`.
    #[inline]
    pub const fn position(&self) -> [f64; 3] {
        self.position
    }

    /// Current entity velocity `[vx, vy, vz]`.
    #[inline]
    pub const fn velocity(&self) -> [f64; 3] {
        self.velocity
    }

    /// Reference to the underlying item stack if not depleted.
    #[inline]
    pub const fn stack(&self) -> Option<&ItemStack> {
        self.stack.as_ref()
    }

    /// Number of items remaining in this entity's stack (0 if depleted).
    #[inline]
    pub fn count(&self) -> u16 {
        self.stack.as_ref().map_or(0, ItemStack::count)
    }

    /// Entity age in ticks.
    #[inline]
    pub const fn age(&self) -> u32 {
        self.age
    }

    /// Pickup delay remaining in ticks.
    #[inline]
    pub const fn pickup_delay(&self) -> u32 {
        self.pickup_delay
    }

    /// Whether this entity is resting on the ground.
    #[inline]
    pub const fn on_ground(&self) -> bool {
        self.on_ground
    }

    /// Whether this entity is alive (not despawned, not marked dead, and stack present).
    #[inline]
    pub fn is_alive(&self) -> bool {
        !self.dead && self.age < DESPAWN_TICKS && self.stack.is_some()
    }

    /// Whether this entity has been removed, despawned, or depleted.
    #[inline]
    pub fn is_dead(&self) -> bool {
        !self.is_alive()
    }

    /// Mark this entity as dead/removed.
    #[inline]
    pub fn mark_dead(&mut self) {
        self.dead = true;
    }

    /// Whether this entity can currently be picked up (`pickup_delay == 0` and alive).
    #[inline]
    pub fn can_pickup(&self) -> bool {
        self.is_alive() && self.pickup_delay == 0
    }

    /// The $0.25 \times 0.25 \times 0.25$ bounding box centered at entity position.
    #[inline]
    pub fn aabb(&self) -> Aabb {
        Aabb::from_entity_pos(self.position, ITEM_WIDTH, ITEM_HEIGHT)
    }

    /// Advance physics motion and collision sweep by one tick using [`crate::world::physics`].
    pub fn tick_physics<W: WorldCollisionView>(&mut self, world: &W) {
        if !self.is_alive() {
            return;
        }

        // 1. Gravity acceleration and terminal velocity clamp
        self.velocity[1] -= ITEM_GRAVITY;
        if self.velocity[1] < ITEM_TERMINAL_VELOCITY {
            self.velocity[1] = ITEM_TERMINAL_VELOCITY;
        }

        // 2. Query colliding boxes for sweep
        let start_box = self.aabb();
        let query_box = start_box
            .expand(self.velocity[0], self.velocity[1], self.velocity[2])
            .inflate(0.1, 0.1, 0.1);
        let colliding_boxes = world.get_colliding_boxes(&query_box);

        // 3. Collision sweep along Y, X, Z (items do not step up blocks: step_height = 0.0)
        let (resolved_delta, on_ground, collided_horiz, _, hit_ceiling, _) = collide_and_sweep(
            &start_box,
            self.velocity,
            &colliding_boxes,
            0.0,
            self.on_ground,
        );

        // 4. Update position
        self.position[0] += resolved_delta[0];
        self.position[1] += resolved_delta[1];
        self.position[2] += resolved_delta[2];

        // 5. Update ground contact and zero velocity on obstacle impacts
        self.on_ground = on_ground;

        if on_ground || hit_ceiling {
            self.velocity[1] = 0.0;
        }
        if collided_horiz {
            if (resolved_delta[0] - self.velocity[0]).abs() > EPSILON {
                self.velocity[0] = 0.0;
            }
            if (resolved_delta[2] - self.velocity[2]).abs() > EPSILON {
                self.velocity[2] = 0.0;
            }
        }

        // 6. Apply drag / friction
        if self.on_ground {
            self.velocity[0] *= GROUND_FRICTION;
            self.velocity[2] *= GROUND_FRICTION;
            self.velocity[1] *= AIR_DRAG_VERTICAL;
        } else {
            self.velocity[0] *= AIR_DRAG_HORIZONTAL;
            self.velocity[1] *= AIR_DRAG_VERTICAL;
            self.velocity[2] *= AIR_DRAG_HORIZONTAL;
        }

        if self.position[1] < VOID_DESPAWN_Y {
            self.mark_dead();
            return;
        }

        // Rest clamp for tiny sub-epsilon speeds
        if self.velocity[0].abs() < VELOCITY_REST_THRESHOLD {
            self.velocity[0] = 0.0;
        }
        if self.velocity[1].abs() < VELOCITY_REST_THRESHOLD {
            self.velocity[1] = 0.0;
        }
        if self.velocity[2].abs() < VELOCITY_REST_THRESHOLD {
            self.velocity[2] = 0.0;
        }
    }

    /// Advance age and decrement pickup delay by one tick.
    pub fn tick_lifecycle(&mut self) {
        if !self.is_alive() {
            return;
        }
        self.age = self.age.saturating_add(1);
        if self.age >= DESPAWN_TICKS {
            self.mark_dead();
        }
        if self.pickup_delay > 0 && self.pickup_delay != PERMANENT_PICKUP_DELAY {
            self.pickup_delay -= 1;
        }
    }

    /// Execute a complete simulation tick: physics sweep followed by lifecycle progression.
    pub fn tick<W: WorldCollisionView>(&mut self, world: &W) {
        self.tick_physics(world);
        self.tick_lifecycle();
    }

    /// Check if another item entity can merge into `self`.
    ///
    /// Conditions (minecraft.wiki `Item_(entity)` rev 3816775):
    /// - Both entities are alive and have distinct entity IDs.
    /// - `other`'s bounding box intersects `self`'s bounding box expanded by
    ///   `0.5 x 0.25 x 0.5`.
    /// - Item stacks can stack together and combined count <= `max_stack`.
    pub fn can_merge_with(&self, other: &ItemEntity) -> bool {
        if !self.is_alive() || !other.is_alive() || self.id == other.id {
            return false;
        }
        let (Some(self_stack), Some(other_stack)) = (&self.stack, &other.stack) else {
            return false;
        };
        if !self_stack.can_stack_with(other_stack) {
            return false;
        }
        let search_box = self.aabb().inflate(
            STACK_MERGE_EXPAND_HORIZONTAL,
            STACK_MERGE_EXPAND_VERTICAL,
            STACK_MERGE_EXPAND_HORIZONTAL,
        );
        if !search_box.intersects(&other.aabb()) {
            return false;
        }
        let combined = self_stack.count() + other_stack.count();
        combined <= self_stack.max_stack()
    }

    /// Attempt to merge `other` into `self`.
    pub fn try_merge(&mut self, other: &mut ItemEntity) -> bool {
        if !self.can_merge_with(other) {
            return false;
        }
        let other_stack = other.stack.take().expect("checked in can_merge_with");
        let self_stack = self.stack.as_mut().expect("checked in can_merge_with");
        let overflow = self_stack.add(other_stack.count());
        debug_assert_eq!(overflow, 0);
        other.mark_dead();
        self.age = self.age.min(other.age);
        self.pickup_delay = self.pickup_delay.max(other.pickup_delay);
        true
    }

    /// Whether this item touches the pickup box around `collector_hitbox`.
    ///
    /// The box is inclusive horizontally and exclusive vertically.
    pub fn in_pickup_reach(&self, collector_hitbox: &Aabb) -> bool {
        let item = self.aabb();
        let horizontal = |axis: usize| {
            item.min[axis] <= collector_hitbox.max[axis] + PICKUP_REACH_HORIZONTAL
                && item.max[axis] >= collector_hitbox.min[axis] - PICKUP_REACH_HORIZONTAL
        };
        horizontal(0)
            && horizontal(2)
            && item.min[1] < collector_hitbox.max[1] + PICKUP_REACH_VERTICAL
            && item.max[1] > collector_hitbox.min[1] - PICKUP_REACH_VERTICAL
    }

    /// Attempt player pickup using a player's hitbox.
    pub fn try_collect(
        &mut self,
        player_id: u32,
        player_box: &Aabb,
        inventory: &mut PlayerInventory,
    ) -> ItemPickupResult {
        if !self.can_pickup() || !self.in_pickup_reach(player_box) {
            return ItemPickupResult::none(self.count());
        }
        let Some(stack) = self.stack.as_ref() else {
            return ItemPickupResult::none(0);
        };

        let collected = inventory.insert_stack(stack);
        if collected == 0 {
            return ItemPickupResult::none(self.count());
        }

        let item_name = stack.item().to_owned();
        let owned_stack = self.stack.take().expect("stack is present");
        let (_, rest) = owned_stack
            .split(collected)
            .expect("collected count is in 1..=stack.count()");
        let remaining = rest.as_ref().map_or(0, ItemStack::count);
        self.stack = rest;
        if remaining == 0 {
            self.mark_dead();
        }

        let packet = TakeItemEntityPacket::new(self.id, player_id, u32::from(collected));
        let event = ItemPickupEvent {
            collected_entity_id: self.id,
            collector_entity_id: player_id,
            item: item_name,
            count: collected,
            packet,
        };

        ItemPickupResult {
            collected_count: collected,
            remaining_count: remaining,
            event: Some(event),
        }
    }

    /// Attempt player pickup using player world coordinates ($0.6 \times 1.8$ player AABB).
    pub fn try_collect_at(
        &mut self,
        player_id: u32,
        player_pos: [f64; 3],
        inventory: &mut PlayerInventory,
    ) -> ItemPickupResult {
        let player_box =
            Aabb::from_entity_pos(player_pos, DEFAULT_PLAYER_WIDTH, DEFAULT_PLAYER_HEIGHT);
        self.try_collect(player_id, &player_box, inventory)
    }
}

/// Merge all nearby matching item entities within the $0.5 \times 0.25 \times 0.5$ merge box.
///
/// Returns the number of successful merges performed.
pub fn merge_nearby_stacks(items: &mut [ItemEntity]) -> usize {
    let mut merges = 0;
    let len = items.len();
    for i in 0..len {
        if !items[i].is_alive() {
            continue;
        }
        for j in (i + 1)..len {
            if !items[i].is_alive() {
                break;
            }
            if !items[j].is_alive() {
                continue;
            }
            let (left, right) = items.split_at_mut(j);
            let item_i = &mut left[i];
            let item_j = &mut right[0];
            // The larger stack survives; on a tie the first processed one does.
            let merged = if item_j.count() > item_i.count() {
                item_j.try_merge(item_i)
            } else {
                item_i.try_merge(item_j)
            };
            if merged {
                merges += 1;
            }
        }
    }
    merges
}

/// World manager container coordinating item physics, stack merging, and pickup events.
#[derive(Debug, Default, Clone)]
pub struct ItemEntityManager {
    items: Vec<ItemEntity>,
}

impl ItemEntityManager {
    /// Create an empty `ItemEntityManager`.
    pub fn new() -> Self {
        Self { items: Vec::new() }
    }

    /// Spawn an item entity into the world.
    pub fn spawn(&mut self, item: ItemEntity) {
        self.items.push(item);
    }

    /// Slice of tracked item entities.
    pub fn items(&self) -> &[ItemEntity] {
        &self.items
    }

    /// Mutable slice of tracked item entities.
    pub fn items_mut(&mut self) -> &mut [ItemEntity] {
        &mut self.items
    }

    /// Total number of tracked item entities.
    pub fn count(&self) -> usize {
        self.items.len()
    }

    /// Whether there are zero tracked item entities.
    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }

    /// Advance the simulation by one tick:
    /// 1. Ticks physics and lifecycle for all items.
    /// 2. Merges nearby compatible stacks.
    /// 3. Removes despawned and dead entities.
    pub fn tick<W: WorldCollisionView>(&mut self, world: &W) {
        for item in &mut self.items {
            item.tick(world);
        }
        merge_nearby_stacks(&mut self.items);
        self.items.retain(ItemEntity::is_alive);
    }

    /// Attempt player pickup for all items intersecting the player bounding box.
    pub fn handle_player_pickup(
        &mut self,
        player_id: u32,
        player_pos: [f64; 3],
        inventory: &mut PlayerInventory,
    ) -> Vec<ItemPickupEvent> {
        let player_box =
            Aabb::from_entity_pos(player_pos, DEFAULT_PLAYER_WIDTH, DEFAULT_PLAYER_HEIGHT);
        let mut events = Vec::new();
        for item in &mut self.items {
            if !item.is_alive() {
                continue;
            }
            let result = item.try_collect(player_id, &player_box, inventory);
            if let Some(event) = result.event {
                events.push(event);
            }
        }
        self.items.retain(ItemEntity::is_alive);
        events
    }
}

