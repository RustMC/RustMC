pub const ITEM_WIDTH: f64 = 0.25;

/// Height of dropped item entity bounding box in blocks (minecraft.wiki `Item_(entity)` rev 3816775).
pub const ITEM_HEIGHT: f64 = 0.25;

/// Downward gravity acceleration applied to item entities per tick in blocks/tick² (minecraft.wiki `Entity`: 0.04).
pub const ITEM_GRAVITY: f64 = 0.04;

/// Terminal downward velocity clamp for item entities in blocks/tick (minecraft.wiki `Entity`: 1.96 fixed-point cap 2.0).
pub const ITEM_TERMINAL_VELOCITY: f64 = -2.0;

/// Horizontal velocity damping factor per tick while airborne (minecraft.wiki `Entity`: 0.98).
pub const AIR_DRAG_HORIZONTAL: f64 = 0.98;

/// Vertical velocity damping factor per tick while airborne (minecraft.wiki `Entity`: 0.98).
pub const AIR_DRAG_VERTICAL: f64 = 0.98;

/// Default slipperiness factor of normal solid blocks (minecraft.wiki `Slipperiness`: 0.6).
pub const DEFAULT_BLOCK_SLIPPERINESS: f64 = 0.6;

