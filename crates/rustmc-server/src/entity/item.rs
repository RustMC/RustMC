pub const PLAYER_DROP_PICKUP_DELAY: u32 = 40;

/// Default pickup delay when dropped from a broken block (minecraft.wiki `Item_(entity)` rev 3816775: 10 ticks = 0.5s).
pub const BLOCK_BREAK_PICKUP_DELAY: u32 = 10;

/// Pickup delay that never counts down, so the item cannot be picked up (minecraft.wiki `Item_(entity)` rev 3816775).
pub const PERMANENT_PICKUP_DELAY: u32 = 32767;

