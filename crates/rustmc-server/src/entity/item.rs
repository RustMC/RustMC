pub const PICKUP_REACH_VERTICAL: f64 = 0.5;

/// Void removal height: preview world minimum Y (0) minus 64 (minecraft.wiki `Item_(entity)` rev 3816775).
pub const VOID_DESPAWN_Y: f64 = -64.0;

