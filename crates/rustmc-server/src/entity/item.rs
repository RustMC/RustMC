//! Dropped item entity physics, stack merging, and player pickup collection.
//!
//! Implements Milestone M5 dropped item mechanics:
//! - Item entities with unique IDs, AABB ($0.25 \times 0.25 \times 0.25$),
//!   age tracking (despawning at 6000 ticks = 5 minutes), and pickup delay.
//! - Deterministic motion physics using [`crate::world::physics`]: gravity
//!   acceleration ($v_y - 0.04$ blocks/tick), terminal downward velocity clamp
//!   ($v_y \ge -2.0$), airborne drag ($0.98$), and ground friction derived from
//!   default block slipperiness ($0.6 \times 0.98 = 0.588$).
//! - Nearby stack merging within a $0.5 \times 0.25 \times 0.5$ box expansion up
//!   to each item's `max_stack`.
//! - Player contact pickup collection into inventory, emitting collection events
//!   and `minecraft:take_item_entity` packet payloads (ID 127).
//!
//! Sources: the packet ID comes from the packet report generated by the official
//! 26.3 server (`minecraft:take_item_entity` = 127), and the field layout from
//! minecraft.wiki `Java_Edition_protocol/Packets` revision 3868170. Pickup
//! reach, permanent pickup delay, void despawn, merge box expansion
//! (`0.5 x 0.25 x 0.5`), and merge survivor follow minecraft.wiki `Item_(entity)`
//! revision 3816775. Gravity 0.04, drag 0.98, and acceleration-before-drag follow
//! minecraft.wiki `Entity` ("Motion of entities", retrieved 13 November 2026);
//! default block slipperiness `0.6` follows minecraft.wiki `Slipperiness`, giving
//! `GROUND_FRICTION = 0.6 * 0.98 = 0.588`.

use crate::item::{ItemStack, ItemStackError};
use crate::java_packets::play::clientbound::TAKE_ITEM_ENTITY;
use crate::java_wire::{frame, put_varint, read_varint};
use crate::world::physics::{
    Aabb, DEFAULT_PLAYER_HEIGHT, DEFAULT_PLAYER_WIDTH, WorldCollisionView, collide_and_sweep,
};
use std::fmt;

